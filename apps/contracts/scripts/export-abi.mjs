// Writes the MandateVault ABI where the TypeScript packages import it from:
//   abi/MandateVault.json  plain JSON
//   abi/MandateVault.ts    `as const`, so viem and wagmi infer argument and event types
//
// Usage: node scripts/export-abi.mjs           write the files
//        node scripts/export-abi.mjs --check   fail if the files are out of date

import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

const raw = execFileSync('forge', ['inspect', 'MandateVault', 'abi', '--json'], {
  cwd: root,
  encoding: 'utf8',
  maxBuffer: 16 * 1024 * 1024,
});
const abi = JSON.parse(raw);
const json = `${JSON.stringify(abi, null, 2)}\n`;

const files = {
  'abi/MandateVault.json': json,
  'abi/MandateVault.ts':
    '// Generated by scripts/export-abi.mjs from src/MandateVault.sol. Do not edit by hand.\n' +
    `export const mandateVaultAbi = ${json.trimEnd()} as const;\n`,
};

let stale = false;
for (const [path, content] of Object.entries(files)) {
  const target = join(root, path);
  if (check) {
    let current = '';
    try {
      current = readFileSync(target, 'utf8');
    } catch {
      // A missing file counts as out of date.
    }
    if (current !== content) {
      console.error(`${path} is out of date. Run: pnpm --filter @agent-gateway/contracts build`);
      stale = true;
    }
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
    console.log(`wrote ${path}`);
  }
}

if (stale) process.exit(1);
